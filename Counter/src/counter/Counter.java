public class Counter {

    public static void main(String[] args) {
        int limite = 10;
        
        System.out.println("A contar de 1 até " + limite + ":");
        
        for (int i = 1; i <= limite; i++) {
            System.out.println(i);
        }
        
        System.out.println("Contagem terminada!");
    }
}
